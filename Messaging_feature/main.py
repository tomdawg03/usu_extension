def send_escalation_email(to_email: str, agent_name: str, user_name: str,
                           user_email: str, user_message: str, chat_log: list[dict]) -> dict:
    """
    Sends the escalation email to the matched agent via Gmail SMTP.
    Returns {success: bool, message: str}
    """
    try:
        html_content = build_email_html(user_name, user_email, user_message, chat_log)

        msg = MIMEMultipart('alternative')
        msg['Subject'] = f'Chat Escalation from {user_name} — needs follow-up'
        msg['From']    = f'{FROM_NAME} <{GMAIL_ADDRESS}>'
        msg['To']      = to_email
        # Optional: reply-to goes directly to the user
        msg.add_header('Reply-To', user_email)

        msg.attach(MIMEText(html_content, 'html'))

        with smtplib.SMTP_SSL('smtp.gmail.com', 465) as server:
            server.login(GMAIL_ADDRESS, GMAIL_APP_PASSWORD)
            server.sendmail(GMAIL_ADDRESS, to_email, msg.as_string())

        return {'success': True, 'message': f'Email sent to {agent_name} ({to_email})'}

    except smtplib.SMTPAuthenticationError:
        return {'success': False, 'message': 'Gmail authentication failed. Check your App Password.'}
    except Exception as e:
        return {'success': False, 'message': str(e)}

