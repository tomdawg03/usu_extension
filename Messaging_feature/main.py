class EscalationRequest(BaseModel):
    county: str
    user_name: str
    user_email: str
    user_message: str          # The unanswered question
    chat_log: list[ChatMessage]
    preferred_agent_email: Optional[str] = None  # Optional: if user picks a specific agent


